create extension if not exists pgcrypto;

-- GlobeChat v2 uses anonymous Supabase Auth so usernames/groups can be secured per user.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[A-Za-z0-9_]{3,24}$'),
  created_at timestamptz not null default now()
);

create table if not exists public.chat_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 60),
  owner_id uuid not null references auth.users(id) on delete cascade,
  passcode_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id uuid references public.chat_groups(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  active boolean not null default true,
  primary key(group_id,user_id)
);

create table if not exists public.messages_v2 (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  content text not null default '' check (char_length(content) <= 500),
  chat_id uuid references public.chat_groups(id) on delete cascade,
  is_global boolean not null default false,
  created_at timestamptz not null default now(),
  check ((is_global and chat_id is null) or ((not is_global) and chat_id is not null))
);

create table if not exists public.attachments (
  id uuid primary key default gen_random_uuid(),
  message_id bigint not null references public.messages_v2(id) on delete cascade,
  storage_path text not null,
  file_name text not null,
  mime_type text not null,
  size_bytes bigint not null check(size_bytes between 1 and 10485760),
  created_at timestamptz not null default now()
);

create table if not exists public.group_access_attempts (
  group_id uuid references public.chat_groups(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  window_started_at timestamptz not null default now(),
  attempts int not null default 0,
  primary key(group_id,user_id)
);

create index if not exists msg_global_time on public.messages_v2(created_at desc) where is_global;
create index if not exists msg_group_time on public.messages_v2(chat_id,created_at desc);
create index if not exists msg_search on public.messages_v2 using gin(to_tsvector('simple',content));

create or replace function public.claim_username(p_username text)
returns text language plpgsql security definer set search_path=public as $$
declare u text:=trim(p_username);
begin
 if auth.uid() is null then raise exception 'Not signed in'; end if;
 if u !~ '^[A-Za-z0-9_]{3,24}$' then raise exception 'Use 3-24 letters, numbers, or underscores'; end if;
 if exists(select 1 from profiles where id=auth.uid()) then
   select username into u from profiles where id=auth.uid();
   return u; -- immutable after first claim
 end if;
 insert into profiles(id,username) values(auth.uid(),u);
 return u;
exception when unique_violation then raise exception 'That username is already taken';
end $$;

create or replace function public.create_private_group(p_name text,p_passcode text)
returns uuid language plpgsql security definer set search_path=public as $$
declare gid uuid;
begin
 if auth.uid() is null then raise exception 'Not signed in'; end if;
 if char_length(trim(p_name)) not between 1 and 60 then raise exception 'Invalid group name'; end if;
 if p_passcode !~ '^[0-9]{6}$' then raise exception 'Passcode must be exactly 6 digits'; end if;
 insert into chat_groups(name,owner_id,passcode_hash)
 values(trim(p_name),auth.uid(),crypt(p_passcode,gen_salt('bf'))) returning id into gid;
 insert into group_members(group_id,user_id,joined_at,active) values(gid,auth.uid(),now(),true);
 return gid;
end $$;

create or replace function public.join_private_group(p_group_id uuid,p_passcode text)
returns boolean language plpgsql security definer set search_path=public as $$
declare h text; a group_access_attempts%rowtype;
begin
 if auth.uid() is null then raise exception 'Not signed in'; end if;
 if exists(select 1 from group_members where group_id=p_group_id and user_id=auth.uid()) then return true; end if;
 select passcode_hash into h from chat_groups where id=p_group_id;
 if h is null then raise exception 'Group not found'; end if;

 insert into group_access_attempts(group_id,user_id) values(p_group_id,auth.uid())
 on conflict do nothing;
 select * into a from group_access_attempts where group_id=p_group_id and user_id=auth.uid() for update;

 if a.window_started_at < now()-interval '24 hours' then
   update group_access_attempts set attempts=0,window_started_at=now()
   where group_id=p_group_id and user_id=auth.uid();
   a.attempts:=0;
 end if;
 if a.attempts>=5 then raise exception 'Five attempts used. Try again after the 24-hour window resets.'; end if;

 if crypt(p_passcode,h)<>h then
   update group_access_attempts set attempts=attempts+1 where group_id=p_group_id and user_id=auth.uid();
   raise exception 'Incorrect passcode';
 end if;

 insert into group_members(group_id,user_id) values(p_group_id,auth.uid()) on conflict do nothing;
 return true;
end $$;

create or replace function public.delete_private_group(p_group_id uuid)
returns boolean language plpgsql security definer set search_path=public as $$
begin
 delete from chat_groups where id=p_group_id and owner_id=auth.uid();
 if not found then raise exception 'Only the group owner can delete this group'; end if;
 return true;
end $$;

