create or replace function public.leave_private_group(p_group_id uuid)
returns boolean language plpgsql security definer set search_path=public as $$
begin
 if exists(select 1 from chat_groups where id=p_group_id and owner_id=auth.uid()) then
   raise exception 'The owner cannot leave their own group. Delete the group instead.';
 end if;
 delete from group_members where group_id=p_group_id and user_id=auth.uid();
 return true;
end $$;

